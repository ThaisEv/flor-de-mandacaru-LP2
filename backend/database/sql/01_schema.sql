-- Flor de Mandacaru
-- 01_schema.sql
-- Cria as tabelas e restrições locais (PK, UNIQUE e CHECK).
-- Execute conectado ao banco flor_de_mandacaru.

BEGIN;

CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    telefone VARCHAR(20)
);

CREATE TABLE endereco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    cep VARCHAR(9) NOT NULL,
    logradouro VARCHAR(150) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    complemento VARCHAR(100),
    bairro VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    estado CHAR(2) NOT NULL,
    CONSTRAINT ck_endereco_estado CHECK (estado ~ '^[A-Z]{2}$')
);

CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    descricao TEXT,
    preco NUMERIC(10,2) NOT NULL,
    quantidade_estoque INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    tipo_produto VARCHAR(20) NOT NULL,
    CONSTRAINT ck_produto_preco CHECK (preco >= 0),
    CONSTRAINT ck_produto_estoque CHECK (quantidade_estoque >= 0),
    CONSTRAINT ck_produto_tipo CHECK (tipo_produto IN ('PLANTA', 'VASO', 'BUQUE', 'ARRANJO')),
    -- Necessária para a FK composta de produto_cor.
    CONSTRAINT uq_produto_id_tipo UNIQUE (id, tipo_produto)
);

CREATE TABLE planta (
    produto_id BIGINT PRIMARY KEY,
    nome_cientifico VARCHAR(150),
    necessidade_agua VARCHAR(100),
    luminosidade VARCHAR(100),
    cuidados TEXT,
    tipo_planta VARCHAR(30),
    possui_flor BOOLEAN,
    epoca_floracao VARCHAR(100),
    tipo_folhagem VARCHAR(100)
);

CREATE TABLE vaso (
    produto_id BIGINT PRIMARY KEY,
    material VARCHAR(80),
    altura NUMERIC(8,2),
    largura NUMERIC(8,2),
    CONSTRAINT ck_vaso_altura CHECK (altura IS NULL OR altura > 0),
    CONSTRAINT ck_vaso_largura CHECK (largura IS NULL OR largura > 0)
);

CREATE TABLE papel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(80) NOT NULL,
    preco_adicional NUMERIC(10,2) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_papel_preco CHECK (preco_adicional >= 0)
);

CREATE TABLE laco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    material VARCHAR(80) NOT NULL,
    preco_adicional NUMERIC(10,2) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_laco_preco CHECK (preco_adicional >= 0)
);

CREATE TABLE buque (
    produto_id BIGINT PRIMARY KEY,
    estilo VARCHAR(80),
    papel_padrao_id BIGINT,
    laco_padrao_id BIGINT
);

CREATE TABLE arranjo (
    produto_id BIGINT PRIMARY KEY,
    estilo VARCHAR(80),
    tamanho VARCHAR(50),
    vaso_padrao_id BIGINT
);

CREATE TABLE imagem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    produto_id BIGINT,
    papel_id BIGINT,
    laco_id BIGINT,
    nome_arquivo VARCHAR(255) NOT NULL,
    caminho VARCHAR(500) NOT NULL,
    finalidade VARCHAR(3) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    principal BOOLEAN NOT NULL DEFAULT FALSE,
    formato VARCHAR(5) GENERATED ALWAYS AS
        (lower(substring(nome_arquivo FROM '\.([^.]+)$'))) STORED,
    ordem INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_imagem_um_proprietario CHECK (
        num_nonnulls(produto_id, papel_id, laco_id) = 1
    ),
    CONSTRAINT ck_imagem_finalidade CHECK (finalidade IN ('ICO', 'CMP', 'EDI', 'GAL')),
    CONSTRAINT ck_imagem_ordem CHECK (ordem >= 0)
);

CREATE TABLE cor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    codigo_hexadecimal VARCHAR(9) NOT NULL,
    descricao VARCHAR(255),
    CONSTRAINT ck_cor_hex CHECK (codigo_hexadecimal ~ '^#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$'),
    CONSTRAINT uq_cor_nome_hex UNIQUE (nome, codigo_hexadecimal)
);

CREATE TABLE produto_cor (
    produto_id BIGINT NOT NULL,
    cor_id BIGINT NOT NULL,
    tipo_produto VARCHAR(20) NOT NULL,
    PRIMARY KEY (produto_id, cor_id),
    CONSTRAINT ck_produto_cor_tipo CHECK (tipo_produto IN ('PLANTA', 'BUQUE', 'ARRANJO'))
);

CREATE TABLE vaso_cor (
    vaso_id BIGINT NOT NULL,
    cor_id BIGINT NOT NULL,
    PRIMARY KEY (vaso_id, cor_id)
);

CREATE TABLE papel_cor (
    papel_id BIGINT NOT NULL,
    cor_id BIGINT NOT NULL,
    PRIMARY KEY (papel_id, cor_id)
);

CREATE TABLE laco_cor (
    laco_id BIGINT NOT NULL,
    cor_id BIGINT NOT NULL,
    PRIMARY KEY (laco_id, cor_id)
);

CREATE TABLE tamanho_buque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(2) NOT NULL UNIQUE,
    quantidade_flores INTEGER NOT NULL,
    CONSTRAINT ck_tamanho_buque_quantidade CHECK (quantidade_flores > 0),
    CONSTRAINT ck_tamanho_buque_codigo CHECK (codigo IN ('PP', 'P', 'M', 'G', 'GG'))
);

CREATE TABLE posicao_buque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tamanho_buque_id BIGINT NOT NULL,
    ordem_selecao INTEGER NOT NULL,
    linha INTEGER NOT NULL,
    coluna INTEGER NOT NULL,
    CONSTRAINT ck_posicao_ordem CHECK (ordem_selecao > 0),
    CONSTRAINT ck_posicao_linha CHECK (linha > 0),
    CONSTRAINT ck_posicao_coluna CHECK (coluna > 0),
    CONSTRAINT uq_posicao_ordem UNIQUE (tamanho_buque_id, ordem_selecao),
    CONSTRAINT uq_posicao_coordenada UNIQUE (tamanho_buque_id, linha, coluna),
    CONSTRAINT uq_posicao_id_tamanho UNIQUE (id, tamanho_buque_id)
);

CREATE TABLE item_composicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_composicao_id BIGINT NOT NULL,
    componente_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    CONSTRAINT ck_item_composicao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_composicao_nao_circular CHECK (produto_composicao_id <> componente_id),
    CONSTRAINT uq_item_composicao UNIQUE (produto_composicao_id, componente_id)
);

CREATE TABLE carrinho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL UNIQUE,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE item_carrinho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrinho_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    CONSTRAINT ck_item_carrinho_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_carrinho_preco CHECK (preco_unitario >= 0)
);

CREATE TABLE personalizacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_carrinho_id BIGINT NOT NULL UNIQUE,
    tamanho_buque_id BIGINT,
    papel_id BIGINT,
    laco_id BIGINT,
    vaso_id BIGINT,
    valor_adicional NUMERIC(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_personalizacao_valor CHECK (valor_adicional >= 0),
    CONSTRAINT uq_personalizacao_id_tamanho UNIQUE (id, tamanho_buque_id)
);

CREATE TABLE item_personalizacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personalizacao_id BIGINT NOT NULL,
    posicao_buque_id BIGINT,
    tamanho_buque_id BIGINT,
    planta_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    CONSTRAINT ck_item_personalizacao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_personalizacao_preco CHECK (preco_unitario >= 0),
    CONSTRAINT ck_item_personalizacao_posicao_tamanho CHECK (
        (posicao_buque_id IS NULL AND tamanho_buque_id IS NULL)
        OR
        (posicao_buque_id IS NOT NULL AND tamanho_buque_id IS NOT NULL AND quantidade = 1)
    ),
    CONSTRAINT uq_item_personalizacao_posicao UNIQUE (personalizacao_id, posicao_buque_id)
);

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    data_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL,
    valor_total NUMERIC(10,2) NOT NULL,
    CONSTRAINT ck_pedido_valor CHECK (valor_total >= 0)
);

CREATE TABLE endereco_pedido (
    pedido_id BIGINT PRIMARY KEY,
    endereco_id BIGINT,
    cep_snapshot VARCHAR(9) NOT NULL,
    logradouro_snapshot VARCHAR(150) NOT NULL,
    numero_snapshot VARCHAR(20) NOT NULL,
    complemento_snapshot VARCHAR(100),
    bairro_snapshot VARCHAR(100) NOT NULL,
    cidade_snapshot VARCHAR(100) NOT NULL,
    estado_snapshot CHAR(2) NOT NULL,
    CONSTRAINT ck_endereco_pedido_estado CHECK (estado_snapshot ~ '^[A-Z]{2}$')
);

CREATE TABLE item_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT,
    produto_codigo_snapshot VARCHAR(20) NOT NULL,
    produto_nome_snapshot VARCHAR(120) NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,
    CONSTRAINT ck_item_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_pedido_preco CHECK (preco_unitario >= 0),
    CONSTRAINT ck_item_pedido_subtotal CHECK (subtotal >= 0)
);

CREATE TABLE personalizacao_pedido (
    item_pedido_id BIGINT PRIMARY KEY,
    tamanho_buque_id BIGINT,
    tamanho_codigo_snapshot VARCHAR(2),
    quantidade_flores_snapshot INTEGER,
    papel_id BIGINT,
    papel_codigo_snapshot VARCHAR(20),
    papel_nome_snapshot VARCHAR(80),
    papel_preco_snapshot NUMERIC(10,2),
    laco_id BIGINT,
    laco_codigo_snapshot VARCHAR(20),
    laco_nome_snapshot VARCHAR(80),
    laco_preco_snapshot NUMERIC(10,2),
    vaso_id BIGINT,
    vaso_codigo_snapshot VARCHAR(20),
    vaso_nome_snapshot VARCHAR(120),
    vaso_preco_snapshot NUMERIC(10,2),
    valor_adicional_snapshot NUMERIC(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_personalizacao_pedido_flores CHECK (
        quantidade_flores_snapshot IS NULL OR quantidade_flores_snapshot > 0
    ),
    CONSTRAINT ck_personalizacao_pedido_valor CHECK (valor_adicional_snapshot >= 0),
    CONSTRAINT ck_personalizacao_pedido_papel_preco CHECK (papel_preco_snapshot IS NULL OR papel_preco_snapshot >= 0),
    CONSTRAINT ck_personalizacao_pedido_laco_preco CHECK (laco_preco_snapshot IS NULL OR laco_preco_snapshot >= 0),
    CONSTRAINT ck_personalizacao_pedido_vaso_preco CHECK (vaso_preco_snapshot IS NULL OR vaso_preco_snapshot >= 0)
);

CREATE TABLE flor_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_pedido_id BIGINT NOT NULL,
    planta_id BIGINT,
    planta_codigo_snapshot VARCHAR(20) NOT NULL,
    planta_nome_snapshot VARCHAR(120) NOT NULL,
    posicao_buque_id BIGINT,
    quantidade INTEGER NOT NULL,
    ordem_selecao_snapshot INTEGER,
    linha_snapshot INTEGER,
    coluna_snapshot INTEGER,
    preco_unitario_snapshot NUMERIC(10,2) NOT NULL,
    CONSTRAINT ck_flor_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_flor_pedido_preco CHECK (preco_unitario_snapshot >= 0),
    CONSTRAINT ck_flor_pedido_posicao_snapshot CHECK (
        (ordem_selecao_snapshot IS NULL AND linha_snapshot IS NULL AND coluna_snapshot IS NULL)
        OR
        (ordem_selecao_snapshot IS NOT NULL AND linha_snapshot IS NOT NULL AND coluna_snapshot IS NOT NULL)
    )
);

CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    metodo VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL,
    data_pagamento TIMESTAMP,
    codigo_transacao VARCHAR(150),
    CONSTRAINT ck_pagamento_valor CHECK (valor >= 0)
);

COMMIT;
